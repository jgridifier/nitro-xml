/**
 * Open+free one stub per format so TurboFan has tiered the hot path before the
 * user's first document open. Best-effort: failures are ignored.
 *
 * @param {{ Handle: new (bytes: Uint8Array) => { openDocument(name: string): void, free(): void } }} glue
 */
export function prewarmOpenPaths(glue) {
  if (!glue?.Handle) return;
  const stubs = [
    ["prewarm.xlsx", minimalXlsx()],
    ["prewarm.docx", minimalDocx()],
    ["prewarm.pptx", minimalPptx()],
  ];
  for (const [name, bytes] of stubs) {
    try {
      let b = bytes;
      const h = new glue.Handle(b);
      b = null;
      try {
        h.openDocument(name);
      } finally {
        try {
          h.free();
        } catch {
          /* ignore */
        }
      }
    } catch {
      /* stub may be rejected; still worth trying other formats */
    }
  }
}
