#!/usr/bin/env node
// SPDX-License-Identifier: MIT
/**
 * TS baseline report (#10): reads perf/baselines/ts-7ce81c1.jsonl and writes perf/BASELINE.md and the
 * static page docs/perf/baseline/index.html. Node ESM, no dependencies beyond ./stats.mjs.
 * Usage: node perf/baseline-report.mjs [input.jsonl]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { median, p95 } from './stats.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(process.argv[2] ?? `${root}/perf/baselines/ts-7ce81c1.jsonl`);
const rows = readFileSync(input, 'utf8').trim().split('\n').map((l) => JSON.parse(l));

const DATE = '2026-10-29';
const GAP = 'GAP - provisional, pending #117 (L/XL fixtures not generated; pad.bin to be replaced)';
const PRIMARY = ['first_paint_ms', 'parse_ms', 'first_render_ms', 'full_render_ms', 'tbt_ms', 'JSHeapUsedSize', 'all_slides_ms'];
const FORMATS = ['xlsx', 'docx', 'pptx'];
const TIERS = ['S', 'M', 'L', 'XL'];
const CELLS = [['cold', 1], ['cold', 4], ['warm', 1], ['warm', 4]];
const cellName = ([m, t]) => `${m} ${t}x`;
const MIB = 1024 * 1024;

// metric -> [display name, divisor]
const disp = (k) => {
  if (k.endsWith('_bytes')) return [k.replace(/_bytes$/, '_MiB'), MIB];
  if (k === 'JSHeapUsedSize' || k === 'JSHeapTotalSize') return [`${k} (MiB)`, MIB];
  return [k, 1];
};
const fmt = (v) => (v === undefined ? '-' : Math.abs(v) >= 100 ? v.toFixed(0) : v.toFixed(1).replace(/\.0$/, ''));

const byFixture = new Map();
for (const r of rows) {
  if (!byFixture.has(r.fixture)) byFixture.set(r.fixture, { format: r.format, tier: r.tier, cells: new Map() });
  const f = byFixture.get(r.fixture);
  const ck = cellName([r.mode, r.cpuThrottle]);
  if (!f.cells.has(ck)) f.cells.set(ck, { n: 0, chrome: new Set(), vals: {} });
  const c = f.cells.get(ck);
  c.n++;
  c.chrome.add(r.chrome);
  for (const [k, v] of Object.entries(r.metrics)) if (typeof v === 'number') (c.vals[k] ??= []).push(v);
}
const chromes = [...new Set(rows.map((r) => r.chrome))].sort();
const stat = (f, cell, k, fn) => {
  const xs = f.cells.get(cell)?.vals[k];
  if (!xs?.length) return undefined;
  return fn(xs) / disp(k)[1];
};

function metricKeys(f) {
  const all = new Set();
  for (const c of f.cells.values()) for (const k of Object.keys(c.vals)) all.add(k);
  const prim = PRIMARY.filter((k) => all.has(k));
  const rest = [...all].filter((k) => !PRIMARY.includes(k)).sort();
  return { prim, rest };
}

// ---- headline + rankings
const fixtures = [...byFixture.entries()].sort(([, a], [, b]) => FORMATS.indexOf(a.format) - FORMATS.indexOf(b.format) || TIERS.indexOf(a.tier) - TIERS.indexOf(b.tier));
const cellNames = CELLS.map(cellName);
const headline = fixtures.map(([name, f]) => [name, ...cellNames.map((c) => fmt(stat(f, c, 'first_paint_ms', median)))]);
const rank = (k) => fixtures.map(([n, f]) => [n, stat(f, 'cold 1x', k, median)]).filter(([, v]) => v !== undefined).sort((a, b) => b[1] - a[1]).slice(0, 5);
const slowest = rank('first_paint_ms');
const hungriest = rank('JSHeapUsedSize');

// ---- Markdown
const esc = (s) => String(s).replace(/\|/g, '\\|');
const mdTable = (head, body) => [`| ${head.map(esc).join(' | ')} |`, `| ${head.map((_, i) => (i ? '---:' : '---')).join(' | ')} |`, ...body.map((r) => `| ${r.map(esc).join(' | ')} |`), ''];
const header = [
  ['TS engine', 'upstream ChristopherVR/ooxml @ e66aaec'],
  ['Measured at', 'nitro-xml commit 7ce81c1'],
  ['Chrome', chromes.join(', ')],
  ['Runner', 'local Linux box via `node perf/run.mjs` (cold n=10, warm n=20 + 1 discarded warm-up)'],
  ['Date', DATE],
  ['Source data', `perf/baselines/${input.split('/').pop()} (${rows.length} samples)`],
];
const rankRows = (xs) => xs.map(([n, v], i) => [i + 1, n, fmt(v)]);
const gapRows = FORMATS.flatMap((fm) => ['L', 'XL'].map((t) => [fm, t, GAP]));
const NOTE1 = 'WASM-beats-TS comparison applies only to S/M until #117 lands; L/XL are provisional.';
const NOTE2 = 'Appending to `history.jsonl` and dashboard visibility are pending #8/#9, so #10 stays open.';

const md = ['# TypeScript engine baseline (#10)', '', '<!-- generated by perf/baseline-report.mjs; do not edit -->', ''];
md.push(...mdTable(['Item', 'Value'], header));
md.push('Times are ms unless noted; heap is MiB. Each per-fixture cell is `median / p95`. Cells: mode (cold/warm) x CPU throttle (1x/4x).', '');
md.push('## Status', '', `- **${NOTE1}**`, `- ${NOTE2}`, '');
md.push('## Headline: first_paint median (ms)', '', ...mdTable(['fixture', ...cellNames], headline));
md.push('## Rankings', '', '**5 slowest fixtures** (cold 1x first_paint median):', '');
md.push(...mdTable(['#', 'fixture', 'first_paint_ms'], rankRows(slowest)));
md.push('**5 most memory-hungry fixtures** (cold 1x JSHeapUsedSize median):', '');
md.push(...mdTable(['#', 'fixture', 'JSHeapUsedSize (MiB)'], rankRows(hungriest)));
md.push(`Corpus measured: ${fixtures.map(([n]) => n).join(', ')} (S/M only).`, '');
md.push('## L/XL', '', ...mdTable(['format', 'tier', 'status'], gapRows), NOTE1, '');
md.push('## Per format and tier', '');

const sections = [];
for (const fm of FORMATS) {
  for (const t of TIERS) {
    const hit = fixtures.find(([, f]) => f.format === fm && f.tier === t);
    if (!hit) {
      md.push(`### ${fm} ${t}`, '', GAP, '');
      sections.push({ title: `${fm} ${t}`, gap: true });
      continue;
    }
    const [name, f] = hit;
    const { prim, rest } = metricKeys(f);
    const head = ['metric', ...cellNames.map((c) => {
      const cc = f.cells.get(c);
      return cc ? `${c} (n=${cc.n}, Chrome ${[...cc.chrome].join('/')})` : c;
    })];
    const body = (ks) => ks.map((k) => [disp(k)[0], ...cellNames.map((c) => {
      const m = stat(f, c, k, median);
      return m === undefined ? '-' : `${fmt(m)} / ${fmt(stat(f, c, k, p95))}`;
    })]);
    md.push(`### ${fm} ${t} (${name})`, '', ...mdTable(head, body(prim)));
    if (rest.length) md.push('Other metrics:', '', ...mdTable(head, body(rest)));
    sections.push({ title: `${fm} ${t} (${name})`, head, prim: body(prim), rest: body(rest) });
  }
}
writeFileSync(`${root}/perf/BASELINE.md`, md.join('\n'));

// ---- HTML
const h = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const htable = (head, body) => `<div class="scroll"><table><thead><tr>${head.map((x) => `<th>${h(x)}</th>`).join('')}</tr></thead><tbody>${body.map((r) => `<tr>${r.map((x, i) => (i ? `<td>${h(x)}</td>` : `<th scope="row">${h(x)}</th>`)).join('')}</tr>`).join('')}</tbody></table></div>`;
const out = [`<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<!-- SPDX-License-Identifier: MIT; generated by perf/baseline-report.mjs -->
<title>TS engine baseline - nitro-xml perf</title>
<style>
:root{--navy:#0b1f3a;--ink:#000;--paper:#fff}
*{box-sizing:border-box}
body{margin:0;font:16px/1.5 system-ui,sans-serif;color:var(--ink);background:var(--paper)}
header{background:var(--navy);color:var(--paper);padding:1rem}
header a{color:var(--paper)}
main{padding:1rem;max-width:72rem;margin:0 auto}
h1{margin:.5rem 0;font-size:1.5rem}
h2{color:var(--navy);border-bottom:2px solid var(--navy);padding-bottom:.2rem;margin-top:2rem}
h3{color:var(--navy);margin:1.5rem 0 .5rem}
.scroll{overflow-x:auto}
table{border-collapse:collapse;width:100%;font-size:.85rem}
th,td{border:1px solid var(--navy);padding:.3rem .5rem;text-align:right;white-space:nowrap}
th:first-child,td:first-child{text-align:left}
thead th{background:var(--navy);color:var(--paper)}
tbody th{text-align:left;font-weight:600}
.meta td{text-align:left;white-space:normal}
.gap{border:2px solid var(--ink);padding:.5rem;font-weight:600}
.note{background:var(--navy);color:var(--paper);padding:.1rem .75rem;border-radius:4px}
</style></head><body>
<header><a href="../../">&larr; nitro-xml</a><h1>TypeScript engine baseline (#10)</h1></header>
<main>
<div class="scroll"><table class="meta">${header.map(([k, v]) => `<tr><th scope="row">${h(k)}</th><td>${h(v.replace(/`/g, ''))}</td></tr>`).join('')}</table></div>
<p>Times in ms unless noted; heap in MiB. Each per-fixture cell is median / p95.</p>
<div class="note"><p><strong>${h(NOTE1)}</strong></p><p>${h(NOTE2.replace(/`/g, ''))}</p></div>
<h2>Headline: first_paint median (ms)</h2>
${htable(['fixture', ...cellNames], headline)}
<h2>Rankings</h2>
<h3>5 slowest (cold 1x first_paint median)</h3>
${htable(['#', 'fixture', 'first_paint_ms'], rankRows(slowest))}
<h3>5 most memory-hungry (cold 1x JSHeapUsedSize median)</h3>
${htable(['#', 'fixture', 'JSHeapUsedSize (MiB)'], rankRows(hungriest))}
<h2>L/XL</h2>
${htable(['format', 'tier', 'status'], gapRows)}
<h2>Per format and tier</h2>`];
for (const s of sections) {
  out.push(`<h3>${h(s.title)}</h3>`);
  if (s.gap) { out.push(`<p class="gap">${h(GAP)}</p>`); continue; }
  out.push(htable(s.head, s.prim));
  if (s.rest.length) out.push('<p>Other metrics:</p>', htable(s.head, s.rest));
}
out.push('</main></body></html>\n');
mkdirSync(`${root}/docs/perf/baseline`, { recursive: true });
writeFileSync(`${root}/docs/perf/baseline/index.html`, out.join('\n'));
console.log(`wrote perf/BASELINE.md and docs/perf/baseline/index.html (${rows.length} samples, ${fixtures.length} fixtures)`);
